#ifndef HITO9_OOD_DATASET_FORMAT_H
#define HITO9_OOD_DATASET_FORMAT_H

#include <stdint.h>

#define HITO9_OOD_MAGIC 0x39444F41U /* "AOD9" */
#define HITO9_OOD_VERSION 1U
#define HITO9_OOD_DIM 64U

typedef enum {
    OOD_QUERY_LOCAL = 0,
    OOD_QUERY_ADVERSARIAL = 1
} OODQueryLabel;

typedef enum {
    OOD_MIX_R = 0,
    OOD_MIX_D = 1,
    OOD_MIX_50_50 = 2
} OODMixMode;

#pragma pack(push, 1)
typedef struct {
    uint32_t magic;
    uint32_t version;
    uint64_t seed;
    uint32_t num_vectors;
    uint32_t dimension;
    uint32_t num_queries;
    uint32_t num_basins;
    float vector_sigma;
    float local_query_sigma;
    uint32_t mix_mode;
    uint32_t local_fraction_percent;
    uint32_t local_basin_fraction_percent;
    uint32_t num_selectivities;
    uint32_t selectivities_deci_percent[7];
} Hito9OODHeader;

typedef struct {
    float values[HITO9_OOD_DIM];
    uint8_t label;
    uint8_t reserved[3];
} Hito9OODQueryRecord;
#pragma pack(pop)

/*
 * Binary layout:
 *   Hito9OODHeader
 *   num_vectors * 64 float32 vectors
 *   num_vectors * uint32 categories
 *   num_queries * Hito9OODQueryRecord
 *
 * Query labels identify the actual source distribution, including within
 * M50/50. Ground Truth is intentionally generated by the benchmark runner
 * from this immutable corpus/query file, not embedded in this generator.
 */

#endif
